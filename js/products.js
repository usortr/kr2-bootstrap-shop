// Функции для работы с каталогом
function getProductById(id) {
  return PRODUCTS.find(product => product.id === id);
}

function getProductsByCategory(category) {
  return PRODUCTS.filter(product => product.category === category);
}

function getAllProducts() {
  return [...PRODUCTS]; // Возвращаем копию, чтобы нельзя было изменить оригинал
}

// Средний рейтинг и количество отзывов.
// Если у товара есть reviewsList — считаем по нему, иначе берём зашитые rating/reviews.
function getProductRating(product) {
  if (product.reviewsList && product.reviewsList.length > 0) {
    const count = product.reviewsList.length;
    const sum = product.reviewsList.reduce((acc, review) => acc + review.rating, 0);
    const average = Math.round((sum / count) * 10) / 10; // округление до 1 знака
    return { average, count };
  }
  return { average: product.rating, count: product.reviews };
}